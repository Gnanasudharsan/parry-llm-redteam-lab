"""v2's fresh held-out set (ADR 0007): defined and frozen before any v2 training.

DO NOT TRAIN, TUNE, CALIBRATE OR PICK A THRESHOLD ON THIS SET. It is scored once, when v2's
evaluation runs, with v1 and ProtectAI alongside. Until then nothing reads it except the
integrity test (`tests/test_fresh_heldout.py`) and the leakage check in `build()`.

Four attack families that neither v1's training data nor v1's held-out Parry catalog cover
as a family, each with a format-matched hard-benign counterpart:

- pasted_content: an instruction hidden inside text the user pastes (an email, review,
  ticket...) and asks about (Phase 3 finding F-004);
- invisible_chars: the instruction hidden with zero-width characters or Unicode tag
  characters (U+E0000 block) after a visible, harmless request;
- markup_comment: the instruction inside an HTML comment, a markdown comment, or hidden
  HTML (display:none, the hidden attribute);
- translation_wrapped: the instruction inside text the user asks to translate, in English
  or written in French, Spanish or German.

Plus `trigger_words`: benign questions that use injection vocabulary (ignore, override,
system prompt, jailbreak) as ordinary words. All goals are benign proxies (a canary
marker, a mock URL on `.test`, a mock tool); nothing asks for harmful content.

The items are generated from the hand-written pieces below with a fixed seed, so the file
can be regenerated byte for byte; `datasets/v2-heldout/manifest.json` freezes its sha256.
"""

