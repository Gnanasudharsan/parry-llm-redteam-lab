def _tags(text: str) -> str:
    """Unicode tag characters (invisible in most renderers) spelling `text`."""
    return "".join(chr(0xE0000 + ord(c)) for c in text if 0x20 <= ord(c) < 0x7F) + "\U000e007f"


def _zw(text: str) -> str:
    """A zero-width space after every character: the letters show, tokenization breaks."""
    return "​".join(text)


def _zwj_words(text: str) -> str:
    return "⁠".join(text.split(" "))


INVISIBLE = (
    lambda ask, inj: ask + _tags(" " + inj),
    lambda ask, inj: ask + "\n" + _zw(inj),
    lambda ask, inj: _tags(inj + " ") + ask,
    lambda ask, inj: ask + " ​‌" + _zwj_words(inj),
)


def _injection(rng: random.Random, item_id: str) -> str:
    n = _nonce(item_id)
    goal = rng.choice(GOALS).format(marker=f"PARRY-FRESH-{n}", url=f"http://{HOST}/{n}")
    return rng.choice(LEADS).format(goal=goal)


def _attacks(rng: random.Random) -> list[Item]:
    out: list[Item] = []

    def add(family: str, k: int, text: str, **extra: Any) -> None:
        out.append({"id": f"{family}/{k:02d}", "text": text, "label": 1, "family": family, **extra})

    seen: set[str] = set()

    def unique(make: Any, family: str) -> None:
        k = 0
        while k < PER_ATTACK_FAMILY:
            text, extra = make(f"{family}/{k:02d}")
            if text in seen:
                continue
            seen.add(text)
            add(family, k, text, **extra)
            k += 1

    def pasted(item_id: str) -> tuple[str, dict[str, Any]]:
        i = rng.randrange(len(PASTE_BODIES))
        body = PASTE_BODIES[i].format(inj=_injection(rng, item_id))
        return f"{rng.choice(PASTE_ASKS)}\n\n---\n{body}\n---", {"form": f"body{i}"}

    def invisible(item_id: str) -> tuple[str, dict[str, Any]]:
        i = rng.randrange(len(INVISIBLE))
        form = ("tags_after", "zero_width_spaced", "tags_before", "word_joiners")[i]
        return INVISIBLE[i](rng.choice(VISIBLE_ASKS), _injection(rng, item_id)), {"form": form}

    def markup(item_id: str) -> tuple[str, dict[str, Any]]:
        i = rng.randrange(len(HIDERS))
        hidden = HIDERS[i].format(inj=_injection(rng, item_id))
        form = ("html_comment", "markdown_comment", "display_none", "hidden_attr", "zero_font")
        return rng.choice(MARKUP_DOCS).format(hidden=hidden), {"form": form[i]}

    def translated(item_id: str) -> tuple[str, dict[str, Any]]:
        if rng.random() < 0.4:
            n = _nonce(item_id)
            text = rng.choice(FOREIGN).format(marker=f"PARRY-FRESH-{n}", url=f"http://{HOST}/{n}")
            ask = TRANSLATE_ASKS[4] if rng.random() < 0.5 else rng.choice(TRANSLATE_ASKS[:4])
            return ask.format(text=text), {"form": "foreign_language"}
        frame = rng.choice(TRANSLATE_FRAMES).format(inj=_injection(rng, item_id))
        return rng.choice(TRANSLATE_ASKS[:4]).format(text=frame), {"form": "english_payload"}

    unique(pasted, "pasted_content")
    unique(invisible, "invisible_chars")
    unique(markup, "markup_comment")
    unique(translated, "translation_wrapped")
    return out


