def _benign() -> list[Item]:
    out: list[Item] = []
    for family, texts in (
        ("pasted_content", BENIGN_PASTED),
        ("invisible_chars", BENIGN_INVISIBLE),
        ("markup_comment", BENIGN_MARKUP),
        ("translation_wrapped", BENIGN_TRANSLATE),
        ("trigger_words", TRIGGER_WORDS),
    ):
        out += [
            {"id": f"benign-{family}/{k:02d}", "text": t, "label": 0, "family": family}
            for k, t in enumerate(texts)
        ]
    return out


def items() -> list[Item]:
    rng = random.Random(SEED)  # noqa: S311 - reproducible generation
    rows = _attacks(rng) + _benign()
    for r in rows:
        r["do_not_train"] = True
    return rows


def dumps(rows: list[Item]) -> str:
    # ASCII escapes keep invisible characters visible in diffs and reviews.
    return "".join(json.dumps(r, ensure_ascii=True, sort_keys=True) + "\n" for r in rows)


def _norm(text: str) -> str:
    return re.sub(r"\s+", " ", re.sub(r"[^\w\s]", " ", text.lower())).strip()


def _shingles(text: str, n: int = 8) -> set[str]:
    w = _norm(text).split()
    return {" ".join(w[i : i + n]) for i in range(max(0, len(w) - n + 1))}


def leakage(rows: list[Item], splits: Path) -> dict[str, Any]:
    """Exact (normalized) and 8-word-shingle overlap with every v1 split and held-out set."""
    keys = {_norm(r["text"]) for r in rows}
    sh = set().union(*(_shingles(r["text"]) for r in rows))
    report: dict[str, Any] = {}
    for path in sorted(splits.glob("*.jsonl")):
        other = [json.loads(x)["text"] for x in path.read_text().splitlines() if x]
        report[path.stem] = {
            "items": len(other),
            "exact": sum(_norm(t) in keys for t in other),
            "shingle8": sum(bool(_shingles(t) & sh) for t in other),
        }
    return report


def build(splits: Path = Path("datasets/external/splits")) -> dict[str, Any]:
    rows = items()
    OUT.mkdir(parents=True, exist_ok=True)
    ITEMS.write_text(dumps(rows))
    manifest = {
        "adr": "docs/adr/0007-v2-fresh-heldout.md",
        "do_not_train": True,
        "seed": SEED,
        "n": len(rows),
        "by_family_label": {
            f"{f}:{lab}": c
            for (f, lab), c in sorted(Counter((r["family"], r["label"]) for r in rows).items())
        },
        "by_form": dict(sorted(Counter(r.get("form", "-") for r in rows if r["label"]).items())),
        "sha256": hashlib.sha256(ITEMS.read_bytes()).hexdigest(),
        "leakage_vs_v1": leakage(rows, splits) if splits.exists() else "not run (splits absent)",
    }
    MANIFEST.write_text(json.dumps(manifest, indent=2) + "\n")
    return manifest


def forbidden_keys() -> set[str]:
    """Normalized texts of the frozen set. A v2 data build must drop (and count) any training
    item whose normalized text is in here, and fail if the frozen file's sha256 changed."""
    frozen = json.loads(MANIFEST.read_text())["sha256"]
    if hashlib.sha256(ITEMS.read_bytes()).hexdigest() != frozen:
        raise RuntimeError("datasets/v2-heldout/items.jsonl changed after it was frozen")
    return {_norm(json.loads(x)["text"]) for x in ITEMS.read_text().splitlines() if x}
